from typing import List, Optional
from uuid import UUID
from fastapi import APIRouter, Header, HTTPException, Query, status
from app.models.report import ReportCreate
from app.models.incident import IncidentResponse, IncidentDetailResponse
from app.models.verification import VerificationCreate, VerificationResponse
from app.services.reporter_service import get_or_create_reporter
from app.services.incident_service import (
    create_or_merge_report,
    list_active_incidents,
    get_incident_with_reports,
)
from app.services.verification_service import cast_verification_vote

router = APIRouter(prefix="/incidents", tags=["Incidents & Reports"])


@router.post("/report", status_code=status.HTTP_201_CREATED)
async def submit_incident_report(
    report_in: ReportCreate,
    x_reporter_token: str = Header(default="anonymous-dev-device", description="Pseudonymous device token generated by frontend")
):
    """
    Zero-Friction Incident Reporting:
    Allows citizens to report incidents without passwords or registration walls.
    Automatically merges duplicate reports of the same incident within the local H3 zone.
    """
    reporter = await get_or_create_reporter(x_reporter_token)
    if reporter.get("is_banned"):
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Device has been banned due to repeated abuse.")

    try:
        result = await create_or_merge_report(report_in, reporter)
        return {
            "message": "Report submitted successfully",
            "incident": result["incident"],
            "report_id": result["report"]["id"]
        }
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))


@router.get("", response_model=List[IncidentResponse])
async def get_live_map_incidents(
    category: Optional[str] = Query(None, description="Filter by category code"),
    h3_res7: Optional[str] = Query(None, description="Filter by macro H3 region"),
    min_trust: float = Query(0.0, ge=0.0, le=1.0, description="Minimum trust score filter"),
    within_hours: Optional[int] = Query(None, ge=1, le=720, description="Only incidents active within the past N hours"),
    include_historical: bool = Query(False, description="Include historical ACLED/NEMA seed incidents"),
):
    """
    Fetches real-time, active and unexpired incidents for rendering on the live Leaflet map.
    Returns blurred/jittered coordinates for sensitive crime categories.
    """
    return await list_active_incidents(
        category_code=category,
        h3_res7=h3_res7,
        min_trust=min_trust,
        within_hours=within_hours,
        include_historical=include_historical,
    )


@router.get("/{incident_id}", response_model=IncidentDetailResponse)
async def get_incident_detail(incident_id: UUID):
    """
    Fetches one incident plus all citizen reports merged into it.
    """
    incident = await get_incident_with_reports(incident_id)
    if not incident:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Incident not found")
    return incident


@router.post("/{incident_id}/verify", response_model=VerificationResponse)
async def verify_incident(
    incident_id: UUID,
    vote_in: VerificationCreate,
    x_reporter_token: str = Header(default="anonymous-dev-device", description="Device token of voter")
):
    """
    Community Verification (Feature 1: One-Tap Community Ping):
    Confirm (+1) or Dispute (-1) an incident.
    Calculates distance weight based on voter's distance from incident.
    """
    reporter = await get_or_create_reporter(x_reporter_token)
    if reporter.get("is_banned"):
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Device is banned.")

    try:
        result = await cast_verification_vote(incident_id, vote_in, reporter)
        return result
    except ValueError as e:
        code = status.HTTP_409_CONFLICT if "yourself" in str(e).lower() else status.HTTP_404_NOT_FOUND
        raise HTTPException(status_code=code, detail=str(e))
